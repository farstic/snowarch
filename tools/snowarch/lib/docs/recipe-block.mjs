// The generated corpus recipe, in one place, rendered into three files.
//
// The recipe embeds the docs pin twice (`fetch`, `checkout --detach`), so it is generated rather
// than asserted — ARC-06's ruling, and `scripts/gen-docs-recipe.mjs` was its first consumer. The
// bump became the second (ARC-06-S05's fix), and ARC-06-S06 adds the two launcher files: the
// Node-free `bootstrap.sh` and `bootstrap.ps1` have to run the SAME git commands as the Node path,
// and a hand-copied shell function is a copy that drifts the first time the recipe changes.
//
// So: one module renders, three files receive, and a parity test diffs all of them. `docs sync
// --print-recipe` is the fourth reader of the same function, which is why it can be compared too.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CORPUS_DIR, MODE, planRecipe, readAreas } from './sync.mjs';

export const RECIPE_TARGET = 'docs/ARCHITECTURE.md';
export const BEGIN = '<!-- DOCS-RECIPE:BEGIN (generated by scripts/gen-docs-recipe.mjs — do not edit) -->';
export const END = '<!-- DOCS-RECIPE:END -->';

/** The launcher marker pair. A comment in both languages, so one spelling serves both files. */
export const launcherBegin = (mode) => `# recipe-begin ${mode}`;
export const LAUNCHER_END = '# recipe-end';

/**
 * The three files, and the platform each is written FOR.
 *
 * The platform is fixed per target rather than read from `process.platform`: `bootstrap.ps1` is a
 * Windows launcher whether it is generated on a Mac or not, and a generated file whose content
 * depended on who ran the generator would fail its own `--check` on the next machine.
 */
export const TARGETS = Object.freeze([
  { id: 'architecture', path: RECIPE_TARGET, platform: 'linux', modes: [MODE.sparse], kind: 'markdown' },
  { id: 'sh', path: 'tools/snowarch/launcher/docs-recipe.sh', platform: 'linux',
    modes: [MODE.sparse, MODE.full], kind: 'launcher' },
  { id: 'ps1', path: 'tools/snowarch/launcher/docs-recipe.ps1', platform: 'win32',
    modes: [MODE.sparse, MODE.full], kind: 'launcher' },
]);

/** The commands themselves, for a fresh checkout. Every other function here is packaging. */
export function recipeLines({ config, areas, mode = MODE.sparse, platform = 'linux' }) {
  return planRecipe({ config, areas, mode, state: { present: false }, platform });
}

/**
 * The note every rendering ends with.
 *
 * It is the LAST line, not a line under the clone, and that placement is forced: in the shell
 * renderings every step but the last ends with a `\` continuation, and a comment on the line after
 * a continuation is joined onto it — which comments out the command that follows. A note in the
 * middle of the chain would therefore delete a step. `#` is a comment in both shells and inside the
 * markdown fence, so one spelling serves all three surfaces.
 */
export const RERUN_NOTE = '# if a step fails with a network error, re-run: a failed run leaves '
  + 'nothing behind, and a re-run of a checkout fetches only what is missing';

/**
 * The steps whose failure must NOT stop the recipe — the same two the Node path swallows, and for
 * the same reasons it gives at `sync.mjs` step 5: before the superproject knows about the path
 * there is nothing to absorb, and a workspace that has not registered the corpus in `.gitmodules`
 * is a legitimate plain-directory checkout, not a failed install.
 *
 * Without this list the fail-fast joiner would make the Node-FREE launchers STRICTER than the Node
 * path — a bootstrap that Node finishes with a note would die at B02 — which is a regression of its
 * own, dressed as a fix. Named by STEP, not by position: a step that moves keeps its ruling.
 */
export const TOLERATED = Object.freeze(['submodule absorbgitdirs', 'submodule init']);

/**
 * The step's name, for the message a failed step throws. Derived from the command rather than
 * carried alongside it, so a new step in `planRecipe` cannot arrive without one.
 */
export function stepName(line) {
  const t = line.replace(/^git /, '').split(' ')
    .filter((x, i, a) => x !== '-c' && x !== '-C' && a[i - 1] !== '-c' && a[i - 1] !== '-C');
  // `submodule` and `sparse-checkout` each front two different steps; one token would name both
  // the same and a thrown message could not tell them apart.
  return (t[0] === 'submodule' || t[0] === 'sparse-checkout') ? `${t[0]} ${t[1]}` : t[0];
}

/**
 * Steps that must not run when their work is already done, with the precondition per surface.
 *
 * WHY: the rendered recipe is `state.present: false` — the FRESH-checkout list — and a launcher
 * runs it on every bootstrap, including the second one. `git clone` refuses a directory that exists
 * and is not empty, so the second run's first step failed. Until the joiner landed, that failure
 * was swallowed along with every other, and the rest of the recipe went on to reconcile the
 * existing checkout; making the recipe fail fast without this guard turned a silently-idempotent
 * recipe into one that dies on its second run. Measured on all three `no-node` CI cells.
 *
 * The test is EXISTS, not is-a-directory: `git submodule absorbgitdirs` — the recipe's own fifth
 * step — migrates the gitdir and leaves `vendor/ServiceNowDocs/.git` as a FILE. A `-d` test would
 * be false on exactly the tree this guard exists for. `sync.mjs`'s `inspect` asks the same question
 * the same way (`existsSync(join(corpus, '.git'))`), which is not a coincidence: this is that
 * function's `if (!state.present)`, rendered for a shell.
 */
export const PRECONDITION = Object.freeze({
  clone: Object.freeze({
    sh: `[ -e ${CORPUS_DIR}/.git ]`,
    // PowerShell's Test-Path matches a file or a directory, and accepts the forward slashes, so one
    // spelling of the path serves both surfaces.
    ps1: `if (-not (Test-Path "${CORPUS_DIR}/.git"))`,
  }),
});

/**
 * Fail fast, rendered per surface from the one list of commands.
 *
 * WHY THIS EXISTS: until ARC-03-C1 the rendered bodies were six commands in sequence with no check
 * of any kind, so a shell function's exit status was its final `echo`'s — always 0. A transient 408
 * at the fetch or the checkout was swallowed whole: `bootstrap.sh`'s `|| die B02` never fired, the
 * install continued, and the doctor reported "area missing" — the symptom, three steps downstream
 * of the cause. Measured on `bootstrap (no-node, macos-latest)`.
 *
 * The two shells need different mechanisms, and neither is the obvious one:
 *   sh   ` && \` between steps. NOT `set -e`: this text is pasted into an interactive shell as
 *        often as it is sourced, and `set -e` there stays set and kills the user's session on their
 *        next failed command. `bootstrap.sh` itself declines `set -e` for a related reason.
 *   ps1  an explicit `$LASTEXITCODE` check after each step. PowerShell before 7.4 does not stop on
 *        a native command's exit code at all, so no preference setting reaches this.
 */
export function joinRecipe(lines, surface) {
  const fatal = (line) => line.startsWith('git ') && !TOLERATED.includes(stepName(line));
  if (surface === 'ps1') {
    const out = [];
    for (const line of lines) {
      const pre = PRECONDITION[stepName(line)];
      if (pre) {
        out.push(`${pre.ps1} {`, `  ${line}`);
        if (fatal(line)) out.push(`  if ($LASTEXITCODE -ne 0) { throw "corpus: ${stepName(line)} failed" }`);
        out.push('}');
        continue;
      }
      out.push(line);
      if (fatal(line)) out.push(`if ($LASTEXITCODE -ne 0) { throw "corpus: ${stepName(line)} failed" }`);
    }
    return [...out, RERUN_NOTE];
  }
  // `{ …; } || true` rather than a bare `… || true`: the precedence of `a || b && c` is genuinely
  // `(a || b) && c` and this chain decides whether a bootstrap dies, so a reader should not have to
  // know that rule to trust it.
  const body = lines.map((l) => {
    const name = stepName(l);
    // A precondition, not a `|| true`: the step is SKIPPED when its work is already done, and still
    // fatal when it runs and fails. Swallowing a clone failure is what this whole story removes.
    if (PRECONDITION[name]) return `{ ${PRECONDITION[name].sh} || ${l} ; }`;
    return TOLERATED.includes(name) ? `{ ${l} || true ; }` : l;
  });
  return [...body.slice(0, -1).map((l) => `${l} && \\`), body[body.length - 1], RERUN_NOTE];
}

/** The markdown block: fenced, between HTML comment markers. */
export function renderRecipeBlock({ config, areas }) {
  const lines = recipeLines({ config, areas });
  // `commands` counts COMMANDS, not rendered lines: the joiners and the note are packaging, and a
  // count that moved when a comment was added would make the generator's own report meaningless.
  return { block: [BEGIN, '', '```sh', ...joinRecipe(lines, 'sh'), '```', '', END].join('\n'),
    commands: lines.length };
}

/** One `<begin>…<end>` region replaced. Returns null when the markers are not both present. */
function splice(doc, begin, end, body) {
  const start = doc.indexOf(begin);
  const stop = doc.indexOf(end, start + begin.length);
  if (start === -1 || stop === -1) return null;
  return doc.slice(0, start) + begin + body + doc.slice(stop);
}

/**
 * Render `target` against the current pin and splice it in.
 *
 *   written    the file changed (or would, with `write: false`)
 *   current    it already holds exactly this
 *   absent     no such file — a fixture tree, not a repository defect
 *   no-markers the file exists but has lost a marker, so nothing could be regenerated
 */
export function applyTarget(target, { root, config, areas = null, write = true }) {
  const path = join(root, target.path);
  if (!existsSync(path)) return { status: 'absent', target: target.id, path: target.path, commands: 0 };

  const resolved = areas ?? readAreas(root, config.docs.areasFile);
  const doc = readFileSync(path, 'utf8');
  let next = doc;
  let commands = 0;

  if (target.kind === 'markdown') {
    const { block, commands: n } = renderRecipeBlock({ config, areas: resolved });
    commands = n;
    const start = doc.indexOf(BEGIN);
    const stop = doc.indexOf(END);
    if (start === -1 || stop === -1 || stop < start) {
      return { status: 'no-markers', target: target.id, path: target.path, commands };
    }
    next = doc.slice(0, start) + block + doc.slice(stop + END.length);
  } else {
    // The file's OWN line ending, not this platform's. `.gitattributes` stores `*.ps1` as
    // `eol=crlf`, so `docs-recipe.ps1` arrives CRLF in every checkout on every OS — and a generator
    // that spliced LF into it would find the file different on the next `--check`, for ever, on a
    // clean tree. Detected from the file rather than assumed from the extension, so a future target
    // gets the same treatment without a second rule.
    const eol = doc.includes('\r\n') ? '\r\n' : '\n';
    for (const mode of target.modes) {
      const lines = recipeLines({ config, areas: resolved, mode, platform: target.platform });
      commands += lines.length;
      // Two-space indent inside the function body, and the marker lines themselves are preserved:
      // the launcher owns the function wrapper, the generator owns only what is between.
      const rendered = joinRecipe(lines, target.platform === 'win32' ? 'ps1' : 'sh');
      const body = `${eol}${rendered.map((l) => `  ${l}`).join(eol)}${eol}`;
      const spliced = splice(next, launcherBegin(mode), LAUNCHER_END, body);
      if (spliced === null) {
        return { status: 'no-markers', target: target.id, path: target.path, commands };
      }
      next = spliced;
    }
  }

  if (next === doc) return { status: 'current', target: target.id, path: target.path, commands };
  if (write) writeFileSync(path, next);
  return { status: 'written', target: target.id, path: target.path, commands };
}

/** Every target. The bump stages whatever came back `written`. */
export function applyAllTargets({ root, config, areas = null, write = true }) {
  return TARGETS.map((t) => applyTarget(t, { root, config, areas, write }));
}

/** Kept for the single-target callers that predate the launcher files. */
export function applyRecipeBlock({ root, config, areas = null, write = true }) {
  return applyTarget(TARGETS[0], { root, config, areas, write });
}
