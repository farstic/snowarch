# `Set-Content -Encoding UTF8` on 5.1 means UTF-8 WITH a BOM, and every file written below is
# read back by something that calls JSON.parse — where a leading BOM is a syntax error, not a
# hint. .NET writes it without one. (Found by CI: Node refused the state this file had just
# written, on the only platform that could have shown it.)
function Write-Json([string]$Path, $Value, [int]$Depth) {
  $json = $Value | ConvertTo-Json -Depth $Depth
  [System.IO.File]::WriteAllText($Path, $json, (New-Object System.Text.UTF8Encoding($false)))
}
function Say([string]$Text) { Write-Host $Text }
function Step([string]$Id, [string]$Title, [string]$Status) { Write-Host ("[{0}/09] {1} … {2}" -f $Id, $Title, $Status) }
function Die([string]$Id, [string]$Cause, [string]$Remedy, [int]$Code) {
  Write-Host ("FAIL {0}: {1}" -f $Id, $Cause)
  if ($Remedy) { Write-Host ("Remedy: {0}" -f $Remedy) }
  exit $Code
}
# The floors, from the generated config: one key per line, which ARC-06-S14 asserts. Read with a
# regex rather than ConvertFrom-Json so the launcher needs nothing of the JSON it cannot parse.
function Floor([string]$Name) {
  $line = Select-String -Path "$Root\engine.config.json" -Pattern ('"' + $Name + '": *"([0-9][0-9.]*)"') | Select-Object -First 1
  if (-not $line) { return '' }
  return $line.Matches[0].Groups[1].Value
}
function VersionGe([string]$Have, [string]$Want) {
  $a = ($Have -split '\.'); $b = ($Want -split '\.')
  for ($i = 0; $i -lt 3; $i++) {
    $x = 0; $y = 0
    if ($i -lt $a.Length) { $x = [int]($a[$i] -replace '[^0-9]', '0') }
    if ($i -lt $b.Length) { $y = [int]($b[$i] -replace '[^0-9]', '0') }
    if ($x -gt $y) { return $true }
    if ($x -lt $y) { return $false }
  }
  return $true
}

# One pass. `--mode live` arrives as two arguments and `--mode=live` as one; a second scanning loop
# for the pair form would be a second place for the two to disagree.
for ($i = 0; $i -lt $args.Length; $i++) {
  $a = [string]$args[$i]
  $Orig += $a
  switch -Regex ($a) {
    '^--mode$'          { if ($i + 1 -lt $args.Length) { $i++; $Mode = [string]$args[$i]; $Orig += $Mode } ; break }
    '^--mode=(.+)$'     { $Mode = $Matches[1]; break }
    '^--docs$'          { if ($i + 1 -lt $args.Length) { $i++; $Docs = [string]$args[$i]; $Orig += $Docs } ; break }
    '^--docs=(.+)$'     { $Docs = $Matches[1]; break }
    '^--yes$'           { $Yes = $true; break }
    '^--reset$'         { $Reset = $true; break }
    '^--skip-claude-check$' { $SkipClaude = $true; break }
    '^--(from|instance-file)(=.*)?$' { $NodeOnly = $true; break }
    '^--json$'          { $NodeOnly = $true; break }
    '^(--help|-h)$'     { Say 'usage: .\bootstrap.cmd [--mode design|live] [--docs sparse|full|skip] [--yes] [--reset]'; exit 0 }
  }
}

# The `✔` and `—` in the shared sentences are UTF-8, and TWO things have to be right for them to
# arrive intact. This file carries a UTF-8 BOM, because 5.1 reads a BOM-less file as the ANSI code
# page and would mangle them before a single line runs; and the console needs telling too, since
# conhost defaults to a code page that prints them as mojibake. A host with no console (a service,
# a redirected pipe) throws on the second one, which is not a reason to stop bootstrapping.
try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 }
catch { Write-Verbose ('console encoding left as-is: ' + $_.Exception.Message) }

