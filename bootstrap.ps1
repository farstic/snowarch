  if ($answer -eq 'q') { exit 0 }
}

$Started = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
$StepStates = New-Object System.Collections.Specialized.OrderedDictionary
function Save-State {
  if (-not (Test-Path "$Root\.local")) { New-Item -ItemType Directory -Path "$Root\.local" | Out-Null }
  $pinLine = Select-String -Path "$Root\engine.config.json" -Pattern '"pin": *"([0-9a-f]*)"' | Select-Object -First 1
  $state = [ordered]@{
    version = 1; product = 'snowarch'; mode = 'design-only'
    docs = [ordered]@{ mode = $Docs; pin = $pinLine.Matches[0].Groups[1].Value }
    node = [ordered]@{ present = $false; version = $null }
    writer = 'powershell'; platform = 'win32'
    registration = 'project'; registrationReason = 'default'; hooksDisabledByBootstrap = $false
    # No chmod on Windows: the directory inherits the user profile's ACL, and the state says so
    # rather than implying a mode nobody applied.
    fileModes = 'acl-inherited'
    startedAt = $Started; updatedAt = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
    steps = $StepStates
  }
  Write-Json "$Root\.local\bootstrap-state.json" $state 5
}
# `$Ms` is the measured duration, when the step measured itself. `inputsHash` stays null on
# purpose: this launcher TIMES a step, it never caches one.
function Record([string]$Id, [string]$Status, [int]$Ms = 0) {
  $StepStates[$Id] = [ordered]@{
    status = $Status; inputsHash = $null
    finishedAt = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'); durationMs = $Ms
  }
  Save-State
}

